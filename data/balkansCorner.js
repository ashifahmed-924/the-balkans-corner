export function formatPrice(price, { compact = false } = {}) {
  if (price === null || price === undefined) {
    return compact ? "View" : "See current menu";
  }
  if (Number.isInteger(price)) return `$${price}`;
  return `$${price.toFixed(2)}`;
}

export function getMenuByCategory(category) {
  return menu.filter((item) => item.category === category);
}

export function getFeaturedBurgers() {
  return menu.filter(
    (item) =>
      item.category === "Burgers" &&
      ["americana-burger", "chicken-classic", "cheese-burger"].includes(item.id)
  );
}

